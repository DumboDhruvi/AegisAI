"""Domain models for AI evaluation and metrics."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator


class MetricType(str, Enum):
    """Supported evaluation metric types."""

    FAITHFULNESS = "faithfulness"
    CORRECTNESS = "correctness"
    ANSWER_RELEVANCE = "answer_relevance"
    CONTEXT_RELEVANCE = "context_relevance"


class EvaluationInput(BaseModel):
    """Input data required for evaluating an AI system response."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    question: str = Field(..., description="User query or prompt evaluated")
    actual_answer: str = Field(..., description="Answer generated by the AI / RAG system")
    expected_answer: str | None = Field(
        default=None,
        description="Ground truth answer (optional, required for correctness metrics)",
    )
    retrieved_context: list[str] = Field(
        default_factory=list,
        description="Context passages or chunks retrieved by the system",
    )
    case_id: str | None = Field(
        default=None,
        description="Optional identifier of the evaluation case or dataset row",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary metadata for the evaluation run",
    )

    @field_validator("question", "actual_answer")
    @classmethod
    def validate_non_empty(cls, value: str, info: Any) -> str:
        stripped = value.strip()
        if not stripped:
            raise ValueError(f"Field '{info.field_name}' must not be empty.")
        return stripped

    @field_validator("retrieved_context")
    @classmethod
    def clean_context(cls, context_list: list[str]) -> list[str]:
        return [item.strip() for item in context_list if item and item.strip()]


class MetricResult(BaseModel):
    """Outcome of evaluating a single metric."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    metric_type: MetricType = Field(..., description="Type of metric evaluated")
    score: float = Field(..., ge=0.0, le=1.0, description="Normalized score between 0.0 and 1.0")
    passed: bool = Field(..., description="Whether score meets or exceeds the required threshold")
    threshold: float = Field(
        default=0.7,
        ge=0.0,
        le=1.0,
        description="Passing threshold score (default: 0.7)",
    )
    reason: str = Field(..., description="Diagnostic rationale for the assigned score")
    details: dict[str, Any] = Field(
        default_factory=dict,
        description="Supplemental metric-specific computation details",
    )

    @field_validator("score", "threshold")
    @classmethod
    def round_float(cls, value: float) -> float:
        return round(value, 4)


class EvaluationResult(BaseModel):
    """Aggregated evaluation result across one or more metrics."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    case_id: str | None = Field(default=None, description="Associated evaluation case ID if any")
    question: str = Field(..., description="Evaluated question")
    actual_answer: str = Field(..., description="Evaluated AI answer")
    passed: bool = Field(..., description="Overall pass flag (true if all metrics passed)")
    composite_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Mean or weighted score across all evaluated metrics",
    )
    metrics: list[MetricResult] = Field(
        ...,
        min_length=1,
        description="Individual metric results",
    )
    evaluated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of evaluation",
    )
